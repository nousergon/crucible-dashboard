_WEEKLY, _PREOPEN, _POSTCLOSE = PIPELINE_STATE_MACHINES


def _section(name: str, body: str, level: str = "##") -> str:
    return f"{level} `{name}`\n\nSome generated prose.\n\n```mermaid\n{body}\n```\n"


GENERATED_DOC = (
    "# Pipeline diagrams (GENERATED — do not edit)\n\n"
    "Generated by scripts/gen_pipeline_diagrams.py from live ASL.\n\n"
    + _section(_WEEKLY, "flowchart TD\n    A[DataPhase1] --> B{Choice}\n    B --> C[Research]")
    + "\n> Cross-state-machine trigger: weekly -> none\n\n"
    + _section(_PREOPEN, "flowchart TD\n    subgraph P[Parallel]\n      X --> Y\n    end")
    + "\n> Fire-and-forget: daemon shutdown triggers `ne-postclose-trading-pipeline`\n\n"
    + _section(_POSTCLOSE, "flowchart TD\n    R[Reconcile] --> S[Stop]")
)


class TestPipelineDocResolution:
    def test_reuses_observation_registry_four_tier_convention(self, monkeypatch, tmp_path):
        monkeypatch.setenv("PIPELINE_DIAGRAMS_PATH", str(tmp_path / "override.md"))
        monkeypatch.setattr(Path, "home", lambda: tmp_path / "home")
        paths = pipeline_diagrams_loader.candidate_paths()
        repo_parent = Path(pipeline_diagrams_loader.__file__).resolve().parents[2]
        assert paths == [
            tmp_path / "override.md",
            Path("/home/ec2-user/alpha-engine-config/private-docs/PIPELINE_DIAGRAMS_GENERATED.md"),
            tmp_path / "home" / "Development" / "alpha-engine-config" / "private-docs" / "PIPELINE_DIAGRAMS_GENERATED.md",
            repo_parent / "alpha-engine-config" / "private-docs" / "PIPELINE_DIAGRAMS_GENERATED.md",
        ]

    def test_without_env_override_starts_at_ec2_path(self, monkeypatch):
        monkeypatch.delenv("PIPELINE_DIAGRAMS_PATH", raising=False)
        paths = pipeline_diagrams_loader.candidate_paths()
        assert len(paths) == 3
        assert paths[0] == Path("/home/ec2-user/alpha-engine-config/private-docs/PIPELINE_DIAGRAMS_GENERATED.md")

    def test_observation_registry_paths_unchanged_by_shared_helper(self, monkeypatch, tmp_path):
        monkeypatch.setenv("OBSERVATION_REGISTRY_PATH", str(tmp_path / "reg.yaml"))
        monkeypatch.setattr(Path, "home", lambda: tmp_path / "home")
        paths = observation_registry_loader._candidate_paths()
        assert paths[0] == tmp_path / "reg.yaml"
        assert paths[1] == Path("/home/ec2-user/alpha-engine-config/private-docs/OBSERVATION_REGISTRY.yaml")
        assert paths[2] == tmp_path / "home" / "Development" / "alpha-engine-config" / "private-docs" / "OBSERVATION_REGISTRY.yaml"
        assert paths[3].parts[-3:] == ("alpha-engine-config", "private-docs", "OBSERVATION_REGISTRY.yaml")

    def test_first_existing_candidate_wins(self, tmp_path):
        first, second, third = tmp_path / "a.md", tmp_path / "b.md", tmp_path / "c.md"
        second.write_text(GENERATED_DOC)
        third.write_text("")
        result = load_pipeline_diagrams([first, second, third])
        assert result.source_path == second
        assert result.searched == (first, second, third)
        assert result.ok


class TestPipelineDiagramExtraction:
    def test_extracts_all_three_diagrams(self, tmp_path):
        doc = tmp_path / "PIPELINE_DIAGRAMS_GENERATED.md"
        doc.write_text(GENERATED_DOC)
        result = load_pipeline_diagrams([doc])
        assert result.ok, result.errors
        assert list(result.diagrams) == list(PIPELINE_STATE_MACHINES)
        assert result.diagrams[_WEEKLY].startswith("flowchart TD")
        assert "B{Choice}" in result.diagrams[_WEEKLY]
        assert "subgraph P[Parallel]" in result.diagrams[_PREOPEN]
        assert result.diagrams[_POSTCLOSE] == "flowchart TD\n    R[Reconcile] --> S[Stop]"

    def test_annotation_mentioning_a_name_is_not_a_section(self):
        # The postclose name appears in prose between diagrams; only the
        # heading defines the section.
        diagrams, errors = extract_diagrams(GENERATED_DOC)
        assert errors == []
        assert "Reconcile" in diagrams[_POSTCLOSE]

    def test_section_may_nest_subheadings_before_its_diagram(self):
        doc = (
            f"## {_WEEKLY}\n\n### Branches\n\n```mermaid\nflowchart TD\n  A-->B\n```\n"
            + _section(_PREOPEN, "flowchart TD\n  C-->D")
            + _section(_POSTCLOSE, "flowchart TD\n  E-->F")
        )
        diagrams, errors = extract_diagrams(doc)
        assert errors == []
        assert diagrams[_WEEKLY] == "flowchart TD\n  A-->B"

    def test_heading_inside_a_code_fence_is_ignored(self):
        doc = (
            f"```text\n## {_WEEKLY}\n```\n"
            + _section(_PREOPEN, "flowchart TD\n  C-->D")
            + _section(_POSTCLOSE, "flowchart TD\n  E-->F")
        )
        diagrams, errors = extract_diagrams(doc)
        assert _WEEKLY not in diagrams
        assert any(_WEEKLY in e and "no section heading" in e for e in errors)

    def test_diagram_does_not_leak_from_next_section(self):
        doc = (
            f"## {_WEEKLY}\n\nNo diagram rendered.\n\n"
            + _section(_PREOPEN, "flowchart TD\n  C-->D")
            + _section(_POSTCLOSE, "flowchart TD\n  E-->F")
        )
        diagrams, errors = extract_diagrams(doc)
        assert _WEEKLY not in diagrams
        assert diagrams[_PREOPEN] == "flowchart TD\n  C-->D"
        assert errors == [f"`{_WEEKLY}`: section has no ```mermaid block."]

    def test_longer_name_does_not_match_shorter(self):
        doc = (
            _section(_WEEKLY + "-v2", "flowchart TD\n  A-->B")
            + _section(_PREOPEN, "flowchart TD\n  C-->D")
            + _section(_POSTCLOSE, "flowchart TD\n  E-->F")
        )
        diagrams, errors = extract_diagrams(doc)
        assert _WEEKLY not in diagrams
        assert len(errors) == 1


class TestPipelineDiagramFailures:
    def test_missing_document_is_a_diagnostic(self, tmp_path):
        result = load_pipeline_diagrams([tmp_path / "nope.md"])
        assert not result.ok
        assert result.source_path is None
        assert result.diagrams == {}
        assert "PIPELINE_DIAGRAMS_GENERATED.md was not found" in result.errors[0]

    def test_unreadable_document_is_a_diagnostic(self, tmp_path):
        doc = tmp_path / "PIPELINE_DIAGRAMS_GENERATED.md"
        doc.write_bytes(b"\xff\xfe\x00 not utf-8 \x80")
        result = load_pipeline_diagrams([doc])
        assert not result.ok
        assert result.diagrams == {}
        assert "could not be read" in result.errors[0]

    def test_document_without_sections_reports_every_state_machine(self, tmp_path):
        doc = tmp_path / "PIPELINE_DIAGRAMS_GENERATED.md"
        doc.write_text("# Pipeline diagrams\n\nnothing here\n")
        result = load_pipeline_diagrams([doc])
        assert not result.ok
        assert len(result.errors) == 3
        for name in PIPELINE_STATE_MACHINES:
            assert any(name in e for e in result.errors)

    @pytest.mark.parametrize(
        ("weekly_section", "expected"),
        [
            (f"## {_WEEKLY}\n\n```mermaid\n\n```\n", "block is empty"),
            (f"## {_WEEKLY}\n\n```python\nprint(1)\n```\n", "no ```mermaid block"),
            (_section(_WEEKLY, "flowchart TD") + _section(_WEEKLY, "flowchart LR"), "2 section headings"),
        ],
    )
    def test_malformed_weekly_section(self, weekly_section, expected):
        doc = weekly_section + _section(_PREOPEN, "flowchart TD\n  C-->D") + _section(_POSTCLOSE, "flowchart TD\n  E-->F")
        diagrams, errors = extract_diagrams(doc)
        assert _WEEKLY not in diagrams
        assert len(errors) == 1 and expected in errors[0]
        assert set(diagrams) == {_PREOPEN, _POSTCLOSE}

    def test_unterminated_fence_is_reported(self):
        doc = _section(_WEEKLY, "flowchart TD\n  A-->B") + _section(_PREOPEN, "flowchart TD\n  C-->D") + (
            f"## {_POSTCLOSE}\n\n```mermaid\nflowchart TD\n  E-->F\n"
        )
        diagrams, errors = extract_diagrams(doc)
        assert _POSTCLOSE not in diagrams
        assert errors == [f"`{_POSTCLOSE}`: ```mermaid block is never closed."]


